"""Agentic RAG prompt 模板。

Step 1:QueryRewriter 用 PROMPT_REWRITE 改写 query。
"""

# 查询改写 prompt(Step 1)。
# 约束:只规范化(口语化→正式/补关键词),不改义;只输出改写后 query,不解释。
PROMPT_REWRITE = (
    "你是查询改写助手,把用户查询改写成更适合知识库(AI/编程/学习笔记)检索的标准化查询。\n"
    "规则:\n"
    "- 口语化→正式(如「咋搞 X」→「如何实现 X」)\n"
    "- 补检索关键词(把口语/简称映射到技术术语,如「那个循环 agent」→「ReAct 循环 agent」)\n"
    "- 规范化表述,但**不改义**(严格保持用户原意)\n"
    "- 如果查询已经足够清晰正式,**原样返回**,不要为了改而改\n"
    "- 只输出改写后的查询本身,不要解释、不要加引号、不要加前缀\n\n"
    "用户查询:{query}\n\n"
    "改写后查询:"
)

# 查询分解 prompt(Step 2)。
# 防护②:强化「单一问题不分解,禁止同义拆分」(验证发现 qwen3 对否定/深问倾向过度分解)。
PROMPT_DECOMPOSE = (
    "把用户查询分解成适合知识库检索的独立子查询(每个子查询能独立检索)。\n"
    "规则:\n"
    "- 对比类(「对比 A 和 B」/「A 和 B 区别/关系」)→ 拆成 [A 是什么, B 是什么, A 和 B 的区别/关系]\n"
    "- 多个并列实体(A、B、C)→ 各自的「是什么」+ 关键的两两/综合对比\n"
    "- **单一问题原样返回(只输出它本身),严禁把一个问题拆成多个同义问法**"
    "(如「X 不能解决什么」不要拆成 4 种近义;「X 怎么生成」不要拆成是什么/机制/如何)\n"
    "- 只输出子查询,每行一个,不要解释、不要编号\n\n"
    "用户查询:{query}\n"
    "子查询:"
)
